def gorsel_uret(prompt, genislik=512, yukseklik=768, max_deneme=4):
    clean = prompt.encode('ascii', 'ignore').decode('ascii')
    clean = ' '.join(clean.split())[:500]
    encoded = urllib.parse.quote(clean)

    for deneme in range(max_deneme):
        try:
            print(f"  Görsel üretiliyor... (deneme {deneme + 1}/{max_deneme})")
            seed = int(time.time()) + deneme
            url = (
                f"https://image.pollinations.ai/prompt/{encoded}"
                f"?width={genislik}&height={yukseklik}&nologo=true&model=flux&seed={seed}"
            )
            r = requests.get(url, timeout=120)
            if r.status_code == 200 and "image" in r.headers.get("content-type", ""):
                img = Image.open(BytesIO(r.content))
                if img.size[0] > 10:
                    print(f"  Görsel üretildi: {img.size}")
                    return img
            time.sleep(5)
        except Exception as e:
            print(f"  Hata: {e}")
            time.sleep(6)

    fallback = Image.new('RGB', (genislik, yukseklik), (10, 10, 10))
    return fallback


