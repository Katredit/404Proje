# 3. OTOMATİK EŞİK MASKESI
#    Görselin köşe piksellerinden arka plan
#    rengini otomatik öğrenir → daha güvenilir
# ─────────────────────────────────────────────
def vazo_maskesi_olustur(vazo_img):
    rgb = vazo_img.convert("RGB")
    arr = np.array(rgb, dtype=np.float32)
    h, w = arr.shape[:2]

    # Köşe piksellerinden arka plan rengini öğren
    koseler = np.array([
        arr[0, 0], arr[0, w-1],
        arr[h-1, 0], arr[h-1, w-1],
        arr[0, w//2], arr[h//2, 0],
        arr[h//2, w-1], arr[h-1, w//2],
    ])
    arkaplan_rengi = np.median(koseler, axis=0)  # [R, G, B]
    print(f"  Arka plan rengi (medyan): {arkaplan_rengi}")

    # Piksel başına arka plan renginden uzaklık (Öklid mesafesi)
    r, g, b = arr[:,:,0], arr[:,:,1], arr[:,:,2]
    mesafe = np.sqrt(
        (r - arkaplan_rengi[0])**2 +
        (g - arkaplan_rengi[1])**2 +
        (b - arkaplan_rengi[2])**2
    )

    # Eşik: arka plana benzeyen pikseller = 0 (siyah), ürün = 255 (beyaz)
    # Eşik değerini dinamik ayarla: arka plan ne kadar koyu/tek renkse eşik düşük olsun
    esik = max(30, np.percentile(mesafe, 15))
    print(f"  Maske eşiği: {esik:.1f}")

    maske = np.where(mesafe < esik, 0, 255).astype(np.uint8)

    maske_img = Image.fromarray(maske, mode='L')

    # Morfoloji: küçük delikleri kapat, kenarları temizle
    maske_img = maske_img.filter(ImageFilter.MaxFilter(9))   # delikleri doldur
    maske_img = maske_img.filter(ImageFilter.MinFilter(5))   # taşan kenarları geri çek
    maske_img = maske_img.filter(ImageFilter.GaussianBlur(radius=3))  # yumuşat

    return maske_img


