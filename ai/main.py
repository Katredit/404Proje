# 4. DESENE SARMA
# ─────────────────────────────────────────────
def deseni_vazoya_sar(vazo_img, desen_img, opaklık=0.80):
    w, h = vazo_img.size
    vazo_rgb = vazo_img.convert("RGB")
    desen = desen_img.convert("RGB").resize((w, h), Image.LANCZOS)

    # Maske
    maske = vazo_maskesi_olustur(vazo_rgb)

    # Vazo aydınlatma haritası (gri ton)
    vazo_gray = vazo_rgb.convert("L")
    vazo_gray_rgb = Image.merge("RGB", [vazo_gray, vazo_gray, vazo_gray])

    # Multiply blend: desen × aydınlatma → 3D görünüm
    blended = ImageChops.multiply(desen, vazo_gray_rgb)
    blended = ImageEnhance.Brightness(blended).enhance(2.0)
    blended = ImageEnhance.Color(blended).enhance(1.5)

    # Opaklık karışımı
    final_desen = Image.blend(vazo_rgb, blended, opaklık)

    # Maske uygula: vazo bölgesi → desen, dışı → beyaz
    beyaz = Image.new("RGB", (w, h), (255, 255, 255))
    sonuc = Image.composite(final_desen, beyaz, maske)
    sonuc = ImageEnhance.Contrast(sonuc).enhance(1.1)
    return sonuc


