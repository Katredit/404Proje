# 6. GÖRSEL → BASE64
# ─────────────────────────────────────────────
def gorsel_to_base64(gorsel):
    buffer = BytesIO()
    gorsel.save(buffer, format="PNG")
    buffer.seek(0)
    return base64.b64encode(buffer.read()).decode("utf-8")


